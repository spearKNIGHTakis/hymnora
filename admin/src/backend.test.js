import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
test('database guards admin content, atomic publishing, concurrency and source privacy',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon;create role authenticated;create schema auth;create schema storage;
 create table auth.users(id uuid primary key,email text);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth,storage to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;
 create table storage.buckets(id text primary key,name text,public boolean);
 create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text);
 alter table storage.objects enable row level security;
 grant select,insert,update,delete on storage.objects to anon,authenticated;
 create policy existing_broad_policy on storage.objects for all to anon,authenticated using(true) with check(true);
 insert into auth.users values('00000000-0000-0000-0000-000000000001','admin@example.test'),('00000000-0000-0000-0000-000000000002','listener@example.test');`);
 const migration=await readFile(new URL('../backend/001_studio.sql',import.meta.url),'utf8');
 await db.exec(migration);
 await db.exec(`insert into hymnora_private.admins(user_id) values('00000000-0000-0000-0000-000000000001');`);
 const role=async(name,id='')=>{await db.exec(`reset role;select set_config('request.jwt.claim.sub','${id}',false);set role ${name};`);};
 await role('anon');
 assert.equal((await db.query('select hymnora_is_admin() as admin')).rows[0].admin,false);
 await assert.rejects(db.query(`select hymnora_save_hymn('{}'::jsonb,null)`),/permission denied/);
 await assert.rejects(db.query(`insert into storage.objects(bucket_id,name) values('hymn-source-documents','private.pdf')`),/row-level security/);
 await role('authenticated','00000000-0000-0000-0000-000000000002');
 await assert.rejects(db.query(`select hymnora_save_hymn('{}'::jsonb,null)`),/Admin access/);
 await assert.rejects(db.query(`insert into storage.objects(bucket_id,name) values('hymn-audio','bad.mp3')`),/row-level security/);
 await role('authenticated','00000000-0000-0000-0000-000000000001');
 const document={number:'PH1',language:'Twi',title:'Test hymn',stanzas:[{kind:'verse',body:'Original reviewed lyrics'}],reviewed:true,status:'review'};
 let draft=(await db.query('select * from hymnora_save_hymn($1::jsonb,null)',[JSON.stringify(document)])).rows[0];
 assert.equal(draft.revision,1);
 await role('anon');assert.equal((await db.query('select * from hymns')).rows.length,0);
 await role('authenticated','00000000-0000-0000-0000-000000000001');
 draft=(await db.query('select * from hymnora_publish_hymn($1::uuid,$2)',[draft.id,draft.revision])).rows[0];
 await role('anon');assert.equal((await db.query('select body from hymn_stanzas')).rows[0].body,'Original reviewed lyrics');
 await assert.rejects(db.query('select * from hymn_drafts'),/permission denied/);
 await role('authenticated','00000000-0000-0000-0000-000000000001');
 draft=(await db.query('select * from hymnora_save_hymn($1::jsonb,$2)',[JSON.stringify({...draft,stanzas:[{kind:'verse',body:'Unpublished edit'}],status:'draft',reviewed:false}),draft.revision])).rows[0];
 await assert.rejects(db.query('select hymnora_save_hymn($1::jsonb,1)',[JSON.stringify({...draft,status:'draft'})]),/another session/);
 await role('anon');assert.equal((await db.query('select body from hymn_stanzas')).rows[0].body,'Original reviewed lyrics');
 await role('authenticated','00000000-0000-0000-0000-000000000001');
 const rec=(await db.query('select * from hymnora_save_recording($1::jsonb)',[JSON.stringify({hymn_id:draft.id,storage_path:'h1/a.mp3',recording_type:'choir',performer:'Test choir',cues:[{position:1,milliseconds:0}]})])).rows[0];
 assert.equal(rec.is_published,false);
 await assert.rejects(db.query('select hymnora_set_recording_publication($1,true)',[rec.id]),/Copy the audio/);
 await db.exec(`insert into storage.objects(bucket_id,name) values('hymn-audio','h1/a.mp3');`);
 await db.query('select hymnora_set_recording_publication($1,true)',[rec.id]);
 await role('anon');assert.equal((await db.query('select * from hymn_recordings')).rows.length,1);
 await role('authenticated','00000000-0000-0000-0000-000000000001');
 await db.query('select hymnora_unpublish_hymn($1,$2)',[draft.id,draft.revision]);
 await role('anon');assert.equal((await db.query('select * from hymns')).rows.length,0);assert.equal((await db.query('select * from hymn_recordings')).rows.length,0);assert.equal((await db.query('select is_visible from hymnora_overrides')).rows[0].is_visible,false);
 await db.exec('reset role');assert.equal((await db.query("select public from storage.buckets where id='hymn-source-documents'")).rows[0].public,false);
 await db.close();
});
